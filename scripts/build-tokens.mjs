// Generates src/styles/tokens.css from the design system's tokens.json (ADR 0015).
import { readFileSync, writeFileSync } from "node:fs";

const source = "design-handoff/design-system/tokens.json";
const target = "src/styles/tokens.css";
const tokens = JSON.parse(readFileSync(source, "utf8"));

// Proposed in ADR 0015 for control borders that need 3:1 contrast. Pending design sign-off.
const controlLine = { name: "control-line", value: { light: "#7F9A8C", dark: "#6E7A75" } };
const colors = [...tokens.color.tokens, controlLine];

const vars = (theme) => colors.map((t) => `  --${t.name}: ${t.value[theme]};`).join("\n");
const shadow = (theme) => tokens.shadow.tokens.map((t) => `  --tl-${t.name}: ${t.value[theme]};`).join("\n");
const sizes = tokens.spacing.tokens.map((t) => `  --${t.name}: ${t.value};`).join("\n");
const themeColors = colors.map((t) => `  --color-${t.name}: var(--${t.name});`).join("\n");
const themeRadius = tokens.radius.tokens.map((t) => `  --radius-${t.name.replace("radius-", "")}: ${t.value};`).join("\n");

const css = `/* Generated by scripts/build-tokens.mjs from ${source}. Do not edit by hand. */
:root {
${vars("light")}
${shadow("light")}
${sizes}
  color-scheme: light;
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${vars("dark").replaceAll("  --", "    --")}
${shadow("dark").replaceAll("  --", "    --")}
    color-scheme: dark;
  }
}
:root[data-theme="dark"] {
${vars("dark")}
${shadow("dark")}
  color-scheme: dark;
}
@theme inline {
${themeColors}
${themeRadius}
  --shadow-card: var(--tl-shadow-card);
  --font-sans: var(--font-inter), "Segoe UI", system-ui, sans-serif;
  --font-mono: var(--font-plex-mono), ui-monospace, Menlo, monospace;
  --font-brand: var(--font-sora), var(--font-inter), sans-serif;
}
`;

writeFileSync(target, css);
console.log(`Wrote ${target}`);
